package ex2026accessControl.evaluation

import crypto.Hash
import rdts.filters.{Filter, PermissionTree}
import replication.authz.ArdtEvent.Payload.{Capability, DeltaCommitment, Revocation}

import java.nio.charset.StandardCharsets
import java.nio.file.{Files, Path, Paths}
import scala.util.Random

/** Renders a [[GeneratedBenchmarkRdtEventGraph]] as a graph in the DOT language, for viewing with Graphviz.
  *
  * Every event becomes a node, with an edge from each of its parents to it. Nodes are labeled with their position
  * in causal order and their author (`R0` being the root replica, the others numbered as in `replicaIds`), and are
  * filled with a color per author. Capability events are drawn as boxes labeled with the write permission they
  * grant, delta events as ellipses labeled with the leaf they write.
  */
class TraceVisualization(generated: GeneratedBenchmarkRdtEventGraph) {

  private val palette = Seq(
    "#e6194b",
    "#3cb44b",
    "#ffe119",
    "#4363d8",
    "#f58231",
    "#911eb4",
    "#46f0f0",
    "#f032e6",
    "#bcf60c",
    "#fabebe",
    "#008080",
    "#e6beff",
    "#9a6324",
    "#fffac8",
    "#800000",
    "#aaffc3",
    "#808000",
    "#ffd8b1",
    "#000075",
    "#808080"
  )

  private val replicaIndex = generated.replicaIds.map(_.getPublic).zipWithIndex.toMap

  private def nodeId(hash: Hash): String = s"\"${hash.toString}\""

  /** The leaf a delta writes, or `?` if it writes none or more than one */
  private def writtenLeaf(commitment: Hash): String =
    generated.deltaValueStore.get(commitment) match {
      case Some(revealed) =>
        val delta = revealed.delta
        BenchmarkRdt.leafPaths.filter(path =>
          Filter[BenchmarkRdt].isAllowed(delta, PermissionTree.fromPath(path))
        ) match {
          case Seq(leaf) => leaf
          case _         => "?"
        }
      case None => "?"
    }

  def toDot: String = {
    val builder = StringBuilder()
    builder ++= "digraph trace {\n"
    builder ++= "  rankdir=TB;\n"
    builder ++= "  node [style=filled, fontname=\"Helvetica\", fontsize=10];\n"

    val events = generated.eventGraph.allEventsInCausalOrder
    events.zipWithIndex.foreach { case ((hash, event), index) =>
      val author               = replicaIndex(event.author)
      val color                = palette(author % palette.size)
      val (shape, description) = event.payload match {
        case Capability(holder, _, write) =>
          val kind = if hash == generated.eventGraph.genesis then "genesis" else s"→ R${replicaIndex(holder)}"
          ("box", s"$kind\\nwrite ${write.toPathStringSet.toSeq.sorted.mkString(", ")}")
        case DeltaCommitment(commitment) => ("ellipse", writtenLeaf(commitment))
        case Revocation(_)               => ("octagon", "revocation")
      }
      builder ++= s"  ${nodeId(hash)} [label=\"#$index R$author\\n$description\", shape=$shape, fillcolor=\"$color\"];\n"
    }

    events.foreach { (hash, event) =>
      event.parents.foreach(parent => builder ++= s"  ${nodeId(parent)} -> ${nodeId(hash)};\n")
    }

    builder ++= "}\n"
    builder.result()
  }

  def writeTo(path: Path): Unit =
    Files.writeString(path, toDot, StandardCharsets.UTF_8): Unit
}

/** Writes a small trace generated by [[TraceGeneration.generateDelegationHierarchyEventGraph]] to a DOT file.
  *
  * Arguments (all optional): output path (default `trace.dot`), number of events in phase 1 (default 20) and in
  * phase 2 (default 30). Render with e.g. `dot -Tsvg trace.dot -o trace.svg`.
  */
object TraceVisualization {
  def main(args: Array[String]): Unit = {
    val output          = Paths.get(args.lift(0).getOrElse("trace.dot"))
    val numEventsPhase1 = args.lift(1).map(_.toInt).getOrElse(20)
    val numEventsPhase2 = args.lift(2).map(_.toInt).getOrElse(30)

    given Random  = Random(42L)
    val generated = TraceGeneration.generateDelegationHierarchyEventGraph(numEventsPhase1, numEventsPhase2, 0.2)

    TraceVisualization(generated).writeTo(output)
    println(s"Wrote ${generated.eventGraph.events.size} events to ${output.toAbsolutePath}")
  }
}
